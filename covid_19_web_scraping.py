import pandas as pd
import requests
from bs4 import BeautifulSoup

# 1. Extract data from website
url = "https://www.worldometers.info/coronavirus/"
html = requests.get(url).text

soup = BeautifulSoup(html, "html.parser")

# 2. Find the main table
table = soup.find("table", attrs={"id": "main_table_countries_today"})
rows = table.find_all("tr")

# 3. Extract rows
data = []

for row in rows:
    row_data = row.text.strip().split("\n")[1:5]
    data.append(row_data)

# 4. Create DataFrame
df = pd.DataFrame(
    data[9:240],
    columns=data[0]
)

# 5. Remove unnecessary column
df.drop("NewCases", axis=1, inplace=True)

# 6. Clean column names
df.rename(
    columns={"Country,Other": "Country"},
    inplace=True
)

# 7. Clean TotalCases
df["TotalCases"] = (
    df["TotalCases"]
    .str.replace(",", "", regex=False)
    .str.strip()
)

df["TotalCases"] = pd.to_numeric(
    df["TotalCases"],
    errors="coerce"
).fillna(0).astype(int)

# 8. Clean TotalDeaths
df["TotalDeaths"] = (
    df["TotalDeaths"]
    .str.replace(",", "", regex=False)
    .str.strip()
)

df["TotalDeaths"] = pd.to_numeric(
    df["TotalDeaths"],
    errors="coerce"
).fillna(0).astype(int)

# 9. Preview the cleaned data
print(df.head())

# 10. Export data
df.to_csv("Data.csv", index=False)

# Optional: Export to Excel
df.to_excel("Data.xlsx", index=False)

print("Data saved successfully!")